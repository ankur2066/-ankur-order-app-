import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
import {resolve} from 'node:path';
const root=process.env.ANKUR_CLIENT_APP||process.cwd();
const core=readFileSync(resolve(root,'src/utils/customerFeatureRollout.ts'),'utf8');
const module=await import('data:text/javascript;charset=utf-8,'+encodeURIComponent(stripTypeScriptTypes(core)));
const hub=readFileSync(resolve(root,'src/components/customer/FeatureHub.tsx'),'utf8');
const owner=readFileSync(resolve(root,'src/components/CustomerFeatureRolloutOwner.tsx'),'utf8');
const admin=readFileSync(resolve(root,'src/components/AdminDashboard.tsx'),'utf8');
const app=readFileSync(resolve(root,'src/App.tsx'),'utf8');
test('first five safe modules work with no live Firebase feature doc',()=>{
 const actual=module.resolvedCustomerFeatures({});
 assert.deepEqual([...actual],['calculator','video','faq','support','service-area']);
 const available=app.slice(app.indexOf("currentTab === 'ai-features'"),app.indexOf("currentTab === 'ai-video'"));
 for(const id of ['calculator','faq','support','service-area'])assert.ok(available.includes("'"+id+"'"));
 assert.match(app,/initial="video" allowed=/);
 assert.match(hub,/const enabled=resolvedCustomerFeatures/);
 assert.match(hub,/doc\(db,'settings','customerFeatureRollout'\)/);
 assert.match(hub,/!allowed\|\|\(allowed\.includes\(f\.id\)&&enabled\.has\(f\.id\)\)/);
});
test('future releases are limited to authorized test UIDs and require explicit pilot',()=>{
 const pilot={pilotEnabled:true,enabledIds:['rates','loyalty','partner'],testerUids:['testUser123456789'],serverReady:false};
 assert.equal(module.resolvedCustomerFeatures({rollout:pilot,uid:'unknownTester123'}).has('rates'),false);
 const visible=module.resolvedCustomerFeatures({rollout:pilot,uid:'testUser123456789'});
 assert.equal(visible.has('rates'),true);
 assert.equal(visible.has('loyalty'),false);
 assert.equal(visible.has('partner'),false);
 assert.equal(module.resolvedCustomerFeatures({rollout:{...pilot,pilotEnabled:false},uid:'testUser123456789'}).has('rates'),false);
 const enabled=module.resolvedCustomerFeatures({rollout:{...pilot,serverReady:true},uid:'testUser123456789',suiteEnabled:true});
 assert.equal(enabled.has('loyalty'),true);
 assert.equal(enabled.has('partner'),true);
 const noSuite=module.resolvedCustomerFeatures({rollout:{...pilot,serverReady:true},uid:'testUser123456789',suiteEnabled:false});
 assert.equal(noSuite.has('partner'),false);
 assert.equal(module.resolvedCustomerFeatures({rollout:{...pilot,enabledIds:['inventory','catalog','reports','unknown','rates']},uid:'testUser123456789'}).has('inventory'),false);
});
